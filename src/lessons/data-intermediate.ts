/** Safety step shared by every stripboard lesson. */
export function safetyStep(placed: string[] = []): LessonStep {
  return {
    id: "safety", title: "Safety and setup",
    text: "Set up the bench before the iron is switched on.",
    detail: "Iron tip ≈ 330–350 °C (lead-free). Battery disconnected the whole time you solder.",
    checklist: [
      "Fume extractor on, beside and slightly behind the joint, pulling flux fumes away from your face. Work in a ventilated room.",
      "Safety glasses on: solder and clipped leads can flick.",
      "The iron always goes back in its stand, never on the bench. Never touch the metal part. Unplug it when you finish.",
      "Wipe the tip on the damp sponge or brass wool, then tin it with a little fresh solder.",
      "Use lead-free solder. No eating or drinking at the bench. Wash your hands after soldering.",
      "Battery disconnected while soldering.",
    ],
    term: { word: "Flux", meaning: "a cleaning agent inside the solder wire. It helps solder flow; its smoke is what the extractor removes." },
    placed, focus: [], tools: true,
  };
}

